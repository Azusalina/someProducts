import assert from 'node:assert/strict';
import { mkdir, mkdtemp, writeFile, readFile, rm, readdir } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { promisify } from 'node:util';
import { execFile } from 'node:child_process';
import { PDFDocument, degrees } from 'pdf-lib';
import { chromium } from 'playwright-core';
import { createToolkit } from '../src/server.js';
import { findChromium } from '../src/core/pdf.js';
const run = promisify(execFile);
const folder = await mkdtemp(path.join(os.tmpdir(), 'toolkit-pdf-pages-'));
const evidence = '/tmp/toolkit-validation/pdf-pages';
await mkdir(evidence, { recursive: true });
const pdf = await PDFDocument.create();
for (let n = 1; n <= 5; n++) {
  const page = pdf.addPage([400 + n * 10, 600 + n * 10]);
  page.drawText(`Original page ${n}`, { x: 35, y: 400, size: 24 });
  if (n === 4) page.setRotation(degrees(90));
}
const originalBytes = await pdf.save();
const filename = path.join(folder, 'original.pdf');
await writeFile(filename, originalBytes);
await writeFile(path.join(folder, 'broken.pdf'), 'Not a PDF');
const app = await createToolkit({ port: 0, baseDir: folder });
const browser = await chromium.launch({ executablePath: await findChromium(), headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage(), errors = [], external = [], writes = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => {
    if (/^https?:/.test(r.url()) && !r.url().startsWith(new URL(app.url).origin)) external.push(r.url());
    if (r.method() === 'POST') writes.push(r.url());
  });
  await page.goto(app.url);
  await page.getByRole('button', { name: 'PDF pages', exact: true }).click();
  assert.equal(await page.locator('#pdf-save').isDisabled(), true);
  await page.locator('#pdf-file').setInputFiles(filename);
  await page.locator('#pdf-selection-count').filter({ hasText: '5 of 5' }).waitFor();
  const importPosts = writes.length;
  await page.locator('#pdf-range').fill('4, 2-3');
  await page.getByRole('button', { name: 'Apply', exact: true }).click();
  const order = () => page.locator('#pdf-page-list li').evaluateAll(rows => rows.map(r => Number(r.dataset.page)));
  assert.deepEqual(await order(), [4, 2, 3]);
  await page.getByRole('button', { name: 'Move page 3 earlier', exact: true }).click();
  assert.deepEqual(await order(), [4, 3, 2]);
  await page.getByRole('button', { name: 'Delete page 3', exact: true }).click();
  assert.deepEqual(await order(), [4, 2]);
  await page.getByRole('button', { name: 'Preview result', exact: true }).click();
  await page.locator('#pdf-status').filter({ hasText: 'Preview updated' }).waitFor();
  // The native PDF extension paints asynchronously after blob navigation.
  await page.waitForTimeout(1200);
  await page.screenshot({ path: `${evidence}/desktop.png`, fullPage: true });
  await page.locator('#pdf-output-name').fill('subset.pdf');
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save as new PDF', exact: true }).click();
  const download = await downloading;
  assert.equal(download.suggestedFilename(), 'subset.pdf');
  await download.saveAs(`${evidence}/subset.pdf`);
  const result = await PDFDocument.load(await readFile(`${evidence}/subset.pdf`));
  assert.equal(result.getPageCount(), 2);
  assert.deepEqual(result.getPages().map(p => p.getWidth()), [440, 420]);
  assert.equal(result.getPage(0).getRotation().angle, 90);
  const { stdout } = await run('pdftotext', [`${evidence}/subset.pdf`, '-']);
  assert.ok(stdout.indexOf('Original page 4') < stdout.indexOf('Original page 2'));
  assert.ok(!stdout.includes('Original page 3'));
  await page.locator('#pdf-range').fill('99');
  await page.getByRole('button', { name: 'Apply', exact: true }).click();
  assert.deepEqual(await order(), [4, 2]);
  await page.locator('#pdf-range-action').selectOption('delete');
  await page.locator('#pdf-range').fill('2,4');
  await page.getByRole('button', { name: 'Apply', exact: true }).click();
  assert.equal(await page.locator('#pdf-save').isDisabled(), true);
  await page.getByRole('button', { name: 'Restore all pages', exact: true }).click();
  assert.deepEqual(await order(), [1, 2, 3, 4, 5]);
  await page.locator('#pdf-file').setInputFiles(path.join(folder, 'broken.pdf'));
  await page.locator('#pdf-status').filter({ hasText: 'Could not open PDF' }).waitFor();
  assert.deepEqual(await order(), [1, 2, 3, 4, 5]);
  const second = await context.newPage(); await second.goto(app.url);
  await second.getByRole('button', { name: 'PDF pages', exact: true }).click();
  assert.equal(await second.locator('#pdf-save').isDisabled(), true);
  await second.close();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole('button', { name: 'Preview result', exact: true }).click();
  await page.locator('#pdf-status').filter({ hasText: 'Preview updated' }).waitFor();
  assert.match(await page.locator('#pdf-open-preview').getAttribute('href'), /^blob:/);
  await page.waitForTimeout(1200);
  await page.screenshot({ path: `${evidence}/mobile.png`, fullPage: true });
  await page.getByRole('button', { name: 'Markdown to PDF', exact: true }).click();
  assert.equal(await page.locator('.file-panel').isVisible(), true);
  assert.equal(await page.locator('#pdf-pages-workspace').isVisible(), false);
  assert.deepEqual(await readFile(filename), Buffer.from(originalBytes));
  assert.deepEqual((await readdir(folder)).sort(), ['broken.pdf', 'original.pdf']);
  assert.equal(writes.length, importPosts); // No PDF upload or export API request.
  assert.deepEqual(external, []); assert.deepEqual(errors, []);
  console.log('PASS PDF page editing: ranges, reorder/delete, result preview, downloaded order/size/rotation/text, invalid input recovery, empty output, original unchanged, tab isolation, mobile, no uploads/external requests.');
} finally { await browser.close(); await app.close(); await rm(folder, { recursive: true, force: true }); }
