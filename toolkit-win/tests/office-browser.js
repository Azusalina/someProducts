import assert from 'node:assert/strict';
import {mkdir,mkdtemp,readFile,rm} from 'node:fs/promises';
import path from 'node:path';
import {tmpdir} from 'node:os';
import {fileURLToPath} from 'node:url';
import {PDFDocument} from 'pdf-lib';
import {chromium,firefox} from 'playwright-core';
import {createToolkit} from '../src/server.js';
import {findChromium} from '../src/core/pdf.js';
const work=await mkdtemp(path.join(tmpdir(),'toolkit-office-browser-'));
const evidence=path.join(tmpdir(),'toolkit-validation','office');await mkdir(evidence,{recursive:true});
const fixture=name=>fileURLToPath(new URL(`./fixtures/office/${name}`,import.meta.url));
const app=await createToolkit({port:0,officeOptions:{workRoot:work}});let browser;
try {
  browser=process.argv.includes('--firefox')?await firefox.launch({headless:true}):await chromium.launch({executablePath:await findChromium(),headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1050},acceptDownloads:true}),page=await context.newPage(),errors=[],external=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(/^https?:/.test(request.url())&&!request.url().startsWith(app.url))external.push(request.url());});
  await page.goto(app.url);await page.waitForFunction(()=>history.state?.toolkitView);
  await page.getByRole('button',{name:'Word / Excel to PDF',exact:true}).click();
  assert.equal(await page.locator('#office-save').isDisabled(),true);
  await page.locator('#office-file').setInputFiles(fixture('document.docx'));
  assert.equal(await page.locator('#office-layout-controls').isVisible(),false);
  await page.locator('#office-convert').click();
  await page.locator('#office-status').filter({hasText:'Ready · 2 pages'}).waitFor({timeout:60000});
  assert.ok(await page.locator('#office-canvas canvas').evaluate(canvas=>canvas.width>100&&canvas.height>100));
  await page.locator('#office-next').click();await page.locator('#office-page').filter({hasText:'Page 2 of 2'}).waitFor();
  await page.locator('#office-previous').click();await page.locator('#office-page').filter({hasText:'Page 1 of 2'}).waitFor();
  await page.locator('#office-name').fill('報告/custom');
  let downloading=page.waitForEvent('download');await page.locator('#office-save').click();let file=await downloading;
  assert.equal(file.suggestedFilename(),'報告_custom.pdf');await file.saveAs(path.join(evidence,'document.pdf'));
  assert.equal((await PDFDocument.load(await readFile(path.join(evidence,'document.pdf')))).getPageCount(),2);
  const frame=await page.locator('.office-preview').boundingBox();assert.ok(frame.width>900);
  await page.screenshot({path:path.join(evidence,'desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'PDF pages',exact:true}).click();
  await page.getByRole('button',{name:'Word / Excel to PDF',exact:true}).click();
  assert.equal(await page.locator('#office-save').isDisabled(),false);
  const second=await context.newPage();await second.goto(app.url);await second.waitForFunction(()=>history.state?.toolkitView);
  await second.getByRole('button',{name:'Word / Excel to PDF',exact:true}).click();
  assert.equal(await second.locator('#office-save').isDisabled(),true);assert.equal(await second.locator('#office-file').evaluate(input=>input.files.length),0);
  await second.locator('#office-file').setInputFiles(fixture('workbook.xlsx'));await second.locator('#office-layout').selectOption('single');
  assert.equal(await second.locator('#office-layout-note').isVisible(),true);
  await second.locator('#office-convert').click();await second.locator('#office-status').filter({hasText:'Ready · 3 pages'}).waitFor({timeout:60000});
  downloading=second.waitForEvent('download');await second.locator('#office-save').click();file=await downloading;
  assert.equal(file.suggestedFilename(),'workbook.pdf');await file.saveAs(path.join(evidence,'workbook.pdf'));
  assert.match(await page.locator('#office-page').textContent(),/1 of 2/);assert.equal(await page.locator('#office-name').inputValue(),'報告/custom');await second.close();
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(250);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.join(evidence,'mobile.png'),fullPage:true});
  await page.locator('#office-file').setInputFiles({name:'not-office.txt',mimeType:'text/plain',buffer:Buffer.from('not an Office file')});
  assert.equal(await page.locator('#office-save').isDisabled(),true);assert.equal(await page.locator('#office-canvas canvas').count(),0);
  await page.locator('#office-convert').click();assert.match(await page.locator('#office-status').textContent(),/DOC, DOCX, XLS or XLSX/);
  let release;
  await page.route('**/api/office/convert?**',async route=>{await new Promise(resolve=>release=resolve);await route.fulfill({status:400,json:{error:'cancelled fixture'}}).catch(()=>{});});
  await page.locator('#office-file').setInputFiles(fixture('document.docx'));await page.locator('#office-convert').click();
  await page.locator('#office-cancel').waitFor();await page.locator('#office-cancel').click();
  await page.locator('#office-status').filter({hasText:'Cancelled.'}).waitFor();release?.();
  await page.getByRole('button',{name:'Customize tools',exact:true}).click();
  assert.equal(await page.getByRole('checkbox',{name:'Word / Excel to PDF',exact:true}).isChecked(),true);
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  console.log('PASS Office PDF: real Word/Excel, visible PDF canvas, pagination, Unicode filename, full preview column, tab isolation, mobile, stale result clearing, cancellation and tool customization.');
}finally{await browser?.close();await app.close();await rm(work,{recursive:true,force:true});}
