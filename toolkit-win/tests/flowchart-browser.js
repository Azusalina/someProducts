import path from 'node:path';
import {tmpdir} from 'node:os';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { chromium,firefox } from 'playwright-core';
import { createToolkit } from '../src/server.js';
import { findChromium } from '../src/core/pdf.js';
const evidence=path.join(tmpdir(),'toolkit-validation','flowchart');
const app = await createToolkit({ port:0 });
const isFirefox=process.argv.includes('--firefox');
const browser = isFirefox?await firefox.launch({headless:true}):await chromium.launch({ executablePath:await findChromium(), headless:true });
try {
  const page = await browser.newPage({ acceptDownloads:true, viewport:{width:1440,height:1000} });
  const external=[],errors=[],endpoints=[];
  page.on('request',r=>{if(r.url().includes('/api/flowchart'))endpoints.push(new URL(r.url()).pathname);});
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(/^https?:/.test(r.url())&&!r.url().startsWith(app.url)) external.push(r.url());});
  await page.goto(app.url); await page.waitForFunction(()=>history.state?.toolkitView);
  await page.getByRole('button',{name:'JS / MJS → SVG',exact:true}).click();
  await page.locator('#code-flowchart-file').setInputFiles({name:'example.mjs',mimeType:'text/javascript',buffer:Buffer.from('export function check(x) { if(x > 0) return x; return 0; }\ncheck(2);')});
  await page.waitForFunction(()=>document.querySelector('#code-flowchart-source').value.includes('export function'));
  assert.equal(await page.locator('#code-flowchart-name').inputValue(),'example.svg');
  await page.locator('#code-flowchart-generate').click();
  await page.locator('#code-flowchart-download').waitFor({state:'visible'});
  await page.waitForFunction(()=>!document.querySelector('#code-flowchart-download').disabled);
  await page.waitForFunction(()=>document.querySelector('#code-flowchart-image').naturalWidth>0);
  await page.locator('#code-flowchart-name').fill('流程图');
  const event=page.waitForEvent('download'); await page.locator('#code-flowchart-download').click();
  const download=await event; assert.equal(download.suggestedFilename(),'流程图.svg');
  const svg=await readFile(await download.path(),'utf8'); assert.match(svg,/<svg/);assert.match(svg,/check/);assert.match(svg,/true/);
  await mkdir(evidence,{recursive:true});
  await download.saveAs(path.join(evidence,'example.svg'));
  await page.screenshot({path:path.join(evidence,'desktop.png'),fullPage:true});
  const second=await browser.newPage(); await second.goto(app.url); await second.getByRole('button',{name:'JS / MJS → SVG',exact:true}).click();
  assert.equal(await second.locator('#code-flowchart-source').inputValue(),'');await second.close();
  await page.locator('#code-flowchart-source').fill('const =');
  assert.equal(await page.locator('#code-flowchart-download').isDisabled(),true);
  await page.locator('#code-flowchart-generate').click();
  await page.locator('#code-flowchart-status').filter({hasText:'Invalid JavaScript'}).waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.join(evidence,'mobile.png'),fullPage:true});
  assert.ok(endpoints.length>0&&endpoints.every(url=>url==='/api/flowchart/source'));
  assert.deepEqual(external,[]);assert.deepEqual(errors,[]);
  console.log((isFirefox?'Firefox: ':'Chromium: ')+'PASS flowchart browser: file input, SVG preview/download, custom Unicode filename, edits invalidate output, syntax errors, independent tabs, mobile, no external requests.');
} finally {await browser.close();await app.close();}
